pub(super) fn is_pictographic(ch: char) -> bool {
    let index = LUCENE_PICTOGRAPHIC.partition_point(|(_, last)| *last < ch);
    LUCENE_PICTOGRAPHIC
        .get(index)
        .is_some_and(|(first, _)| *first <= ch)
}
